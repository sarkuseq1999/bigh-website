"""Build About's "Our promise" pictures: the four dots in colour (Mo picked A, November 12, 2026).

Mo asked for About's last three parts to take the site's California colour, one part at a time.
Of three ideas for Our promise (A the same dots in colour, B four California wildflowers, C one
poppy counting from bud to bloom) he compared B and C, then said "Let's try A". The four grey ink
dots (dark to pale) become four loose watercolour blooms in the colours of the page's own
paintings: poppy orange, golden-hill straw, Pacific blue, sage green (Codex painting
dots-colour-2, prompts/_style.txt + prompts/dots-colour.txt).

The sheet's paper is divided out (the dots multiply onto the page, as the grey ones did) and each
dot is cut into a square with the same room round it as in the mockup Mo picked from
(cut_promise.py), all four on one scale and one middle line.

    python -X utf8 reference/ink-pages/about-promise/build_about_promise.py

Out: public/images/about-promise/dot-colour-<1..4>-v1.webp and src/components/about/promise-art.ts
(the grey dots stay in about-art.ts, which build_bc.py writes).
"""

from pathlib import Path

from cut_promise import ROOM, cut, divide_paper, four, load, paint_mask

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
URL = "/images/about-promise"
SITE = ROOT / "public" / URL.lstrip("/")
ART = ROOT / "src" / "components" / "about" / "promise-art.ts"
TAKE = "dots-colour-2"
NAME = "dot-colour-{k}-v1"


def main():
    SITE.mkdir(parents=True, exist_ok=True)
    a = divide_paper(load(TAKE))
    boxes = four(paint_mask(a))
    side = int(max(max(b[2] - b[0], b[3] - b[1]) for b in boxes) * (1 + 2 * ROOM))
    cy = (min(b[1] for b in boxes) + max(b[3] for b in boxes)) / 2
    entries = []
    for k, box in enumerate(boxes, 1):
        img = cut(a, box, side, cy)
        name = NAME.format(k=k)
        img.save(SITE / f"{name}.webp", quality=90, method=6)
        print(name, img.size, (SITE / f"{name}.webp").stat().st_size)
        entries.append(f'  {{\n    src: "{URL}/{name}.webp",\n    width: {img.width},\n    height: {img.height},\n  }},\n')
    ART.write_text(
        "// Generated by reference/ink-pages/about-promise/build_about_promise.py. Do not edit by hand.\n"
        "// The About page's promise dots in colour (Mo picked A, November 12, 2026): poppy orange,\n"
        "// golden-hill straw, Pacific blue and sage green watercolour, their paper divided out so they\n"
        "// multiply onto the page, each in a square with the same room round it.\n"
        "export const dots = [\n" + "".join(entries) + "] as const;\n",
        encoding="utf-8",
        newline="\n",
    )
    print(ART.relative_to(ROOT))


if __name__ == "__main__":
    main()
