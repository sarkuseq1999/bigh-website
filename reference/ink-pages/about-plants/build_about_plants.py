"""Build the About plants map's pictures (Mo picked A, the map, November 6, 2026).

"Each plant, from where it grows best.": the world painted in ink (Codex over the real land,
ref/land-guide.png), the four plants (cut from the specimens painting) standing at their places;
the page lays the gold trails home to California (plants-map.tsx). Of the round's other ideas,
B (four homes) and C (one plant) were not picked: their paintings went to bigh-archive.

    python -X utf8 reference/ink-pages/about-plants/build_about_plants.py

Out: public/images/about-plants/*.webp and src/components/about/plants-art.ts.
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SITE = ROOT / "public" / "images" / "about-plants"
ART = ROOT / "src" / "components" / "about" / "plants-art.ts"
FLOOR = 10
FADE = 40

TAKES = {
    "map": "map-1-a",
    "specimens": "specimens-1-a",
}
# The places' pixels on the 1536 x 1024 land guide (render_land.py prints them).
PLACES = {
    "california": (187, 359),
    "propolis": (659, 717),
    "turmeric": (1422, 518),
    "grape": (1005, 310),
    "pine": (930, 304),
}
# Each plant's box on the 1024 x 1024 specimens painting (its neighbours' tips cut away).
BOXES = {
    "propolis": (40, 80, 480, 535),
    "turmeric": (505, 15, 1010, 530),
    "grape": (45, 550, 425, 970),
    "pine": (480, 615, 985, 960),
}


def paperless(name):
    """The painting with its paper divided out: white = no paint, so it multiplies onto the page."""
    a = np.asarray(Image.open(HERE / "originals" / f"{name}.png").convert("RGB")).astype(float)
    edge = np.concatenate([a[:40].reshape(-1, 3), a[:, :40].reshape(-1, 3), a[:, -40:].reshape(-1, 3)])
    paper = np.percentile(edge, 60, axis=0)
    dark = 255.0 - np.clip(a / paper * 255.0, 0, 255)
    dark = np.clip((dark - FLOOR) / (1 - FLOOR / 255.0), 0, 255)
    h, w = dark.shape[:2]
    ramp = lambda n: np.clip(np.minimum(np.arange(n), np.arange(n)[::-1]) / FADE, 0, 1)
    dark *= (ramp(h)[:, None] * ramp(w)[None, :])[..., None]
    return Image.fromarray((255.0 - dark).astype(np.uint8))


def trim(img, pad=24, level=14):
    c = np.asarray(img)
    ys, xs = np.where((255 - c.min(axis=2)) > level)
    box = (
        max(int(xs.min()) - pad, 0),
        max(int(ys.min()) - pad, 0),
        min(int(xs.max()) + 1 + pad, img.width),
        min(int(ys.max()) + 1 + pad, img.height),
    )
    return img.crop(box), box


def save(img, name, quality=90):
    SITE.mkdir(parents=True, exist_ok=True)
    img.save(SITE / f"{name}.webp", quality=quality, method=6)
    return {"src": f"/images/about-plants/{name}.webp", "width": img.width, "height": img.height}


def main():
    art = {}
    # The map, cropped to its ink; the places move with the crop (render_land's frame).
    m = paperless(TAKES["map"])
    if m.size != (1536, 1024):
        m = m.resize((1536, 1024), Image.LANCZOS)
    m, (x0, y0, x1, y1) = trim(m, pad=8, level=18)
    art["map"] = save(m, "map-v2")
    art["map"]["places"] = {
        k: [round((x - x0) / m.width, 4), round((y - y0) / m.height, 4)] for k, (x, y) in PLACES.items()
    }
    art["map"]["crop"] = [x0, y0, x1, y1]
    # The four plants, cut from the specimens painting.
    s = paperless(TAKES["specimens"])
    for key, box in BOXES.items():
        q, _ = trim(s.crop(box), pad=10, level=22)
        art[f"plant-{key}"] = save(q, f"plant-{key}-v2")
    ART.write_text(
        "// Generated by reference/ink-pages/about-plants/build_about_plants.py. Do not edit by hand.\n"
        f"export const plantsArt = {json.dumps(art, indent=2)} as const;\n",
        encoding="utf-8",
        newline="\n",
    )
    print(json.dumps(art, indent=1))


main()
