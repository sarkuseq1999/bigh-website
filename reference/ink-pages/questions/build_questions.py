"""Build the Questions paintings (one per question, on every product page) for the site.

usage: python -X utf8 build_questions.py [repo root]   (default: this repository)

originals/<product>-<key>.png (Codex, on Mo's ChatGPT plan) -> public/images/products/<slug>/ink/
q-<key>-v<N>.webp, and src/components/product/ink/questions-art.ts. Each painting has its paper
divided out (the 75th percentile of its border, so it multiplies onto the page's own paper), is cut
to 3:2 round its brushwork (the 4:3 originals kept a wide band of bare paper above and below, which
opened gaps round the answer), and has its outer 7% faded to white, so no edge of the picture shows.
All are one shape, so the answer under each sits at the same height whichever question is picked.
"""

import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

HERE = Path(__file__).parent
ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2]
WIDTH = 1200  # twice the 600-640px the painting takes beside the questions
ASPECT = 3 / 2  # every painting the same shape, so each answer sits at the same height
PAD = 0.07  # bare paper kept round the brushwork, as a share of the original picture
VERSION = 1

# Each product's questions, in the order of its `faq` (the keys name the files and the exports).
PRODUCTS = {
    "nuricell": ("nuricell", ["take", "month", "capsule", "studied", "doctor", "pregnancy"]),
    "advanced-opc": ("opc", ["what", "take", "month", "capsule", "studied", "doctor"]),
    "green-bee-propolis": (
        "propolis",
        ["take", "month", "capsule", "bees", "studied", "pregnancy"],
    ),
    "nature-calm": ("nature-calm", ["take", "month", "capsule", "studied", "doctor"]),
    "turmerific": ("turmerific", ["take", "month", "part", "studied", "doctor"]),
}


def crop_box(out: np.ndarray) -> tuple[int, int, int, int]:
    """The brushwork's box (its faint outliers left out), padded by PAD of the picture on each side,
    then widened or deepened to ASPECT around its middle and kept inside the picture."""
    h, w, _ = out.shape
    dark = np.asarray(Image.fromarray(out.min(axis=2).astype(np.uint8)).filter(ImageFilter.MinFilter(5))) < 215
    ys, xs = np.where(dark)
    y0, y1 = np.percentile(ys, [0.2, 99.8])
    x0, x1 = np.percentile(xs, [0.2, 99.8])
    x0, x1, y0, y1 = x0 - PAD * w, x1 + PAD * w, y0 - PAD * h, y1 + PAD * h
    cw, ch = x1 - x0, y1 - y0
    if cw / ch < ASPECT:
        cw = ch * ASPECT
    else:
        ch = cw / ASPECT
    cw, ch = min(cw, w), min(ch, h)
    if cw / ch > ASPECT:
        cw = ch * ASPECT
    else:
        ch = cw / ASPECT
    cx = min(max((x0 + x1) / 2, cw / 2), w - cw / 2)
    cy = min(max((y0 + y1) / 2, ch / 2), h - ch / 2)
    return round(cx - cw / 2), round(cy - ch / 2), round(cx + cw / 2), round(cy + ch / 2)


def ink(path: Path) -> Image.Image:
    im = np.asarray(Image.open(path).convert("RGB")).astype(np.float32)
    h, w, _ = im.shape
    b = max(8, int(min(h, w) * 0.03))
    border = np.concatenate(
        [im[:b].reshape(-1, 3), im[-b:].reshape(-1, 3), im[:, :b].reshape(-1, 3), im[:, -b:].reshape(-1, 3)]
    )
    paper = np.percentile(border, 75, axis=0)
    out = np.clip(im / paper * 255.0, 0, 255)
    left, top, right, bottom = crop_box(out)
    out = out[top:bottom, left:right]
    h, w, _ = out.shape
    fy = np.clip(np.minimum(np.arange(h), np.arange(h)[::-1]) / (h * 0.07), 0, 1)
    fx = np.clip(np.minimum(np.arange(w), np.arange(w)[::-1]) / (w * 0.07), 0, 1)
    f = np.minimum.outer(fy, fx)[..., None]
    f = f * f * (3 - 2 * f)
    out = 255 - (255 - out) * f
    picture = Image.fromarray(out.round().astype(np.uint8))
    return picture.resize((WIDTH, round(WIDTH / ASPECT)), Image.LANCZOS)


def camel(key: str) -> str:
    head, *rest = key.split("-")
    return head + "".join(word.title() for word in rest)


lines = [
    "// Generated by reference/ink-pages/questions/build_questions.py. Do not edit by hand: change the",
    "// script and run it again. The Questions paintings (Mo's pick A, October 26, 2026): one per",
    "// question, Codex on Mo's ChatGPT plan, the paper divided out so each multiplies onto the page.",
    "export const questionsArt = {",
]
for slug, (prefix, keys) in PRODUCTS.items():
    out_dir = ROOT / "public" / "images" / "products" / slug / "ink"
    out_dir.mkdir(parents=True, exist_ok=True)
    lines.append(f"  {camel(prefix)}: {{")
    for key in keys:
        picture = ink(HERE / "originals" / f"{prefix}-{key}.png")
        name = f"q-{key}-v{VERSION}.webp"
        picture.save(out_dir / name, quality=82, method=6)
        size = (out_dir / name).stat().st_size // 1024
        print(f"{slug}/{name} {picture.width}x{picture.height} {size} KB")
        lines.append(
            f'    {camel(key)}: {{ src: "/images/products/{slug}/ink/{name}", '
            f"width: {picture.width}, height: {picture.height} }},"
        )
    lines.append("  },")
lines.append("} as const;")
target = ROOT / "src" / "components" / "product" / "ink" / "questions-art.ts"
target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print("wrote", target)
