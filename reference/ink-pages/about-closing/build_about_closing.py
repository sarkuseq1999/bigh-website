"""Build About's "Curious about the science?" painting: the tide pool (Mo picked B, November 13, 2026).

Mo asked for About's last three parts to take the site's California colour, one part at a time.
Of three ideas for the closing (A the grey glasses repainted in colour, B a tide pool with a guide,
C a field notebook by a creek) he picked B: low tide on the Monterey coast, a curious older woman
looks into a tide pool with a hand lens while a park naturalist kneels beside her and points to a
sea star (Codex painting tidepool-1, prompts/_style.txt + prompts/tidepool.txt).

The painting's paper is divided out (it multiplies onto the page, as the grey glasses did) and it
is cropped to its paint with a little room, the crop's edge faded to white (cut_closing.py).

    python -X utf8 reference/ink-pages/about-closing/build_about_closing.py

Out: public/images/about-closing/tidepool-v1.webp and src/components/about/closing-art.ts (the grey
glasses stay in about-art.ts, which build_bc.py writes).
"""

from pathlib import Path

from cut_closing import cut

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
URL = "/images/about-closing"
SITE = ROOT / "public" / URL.lstrip("/")
ART = ROOT / "src" / "components" / "about" / "closing-art.ts"
TAKE = "tidepool-1"
NAME = "tidepool-v1"


def main():
    SITE.mkdir(parents=True, exist_ok=True)
    img = cut(TAKE)
    img.save(SITE / f"{NAME}.webp", quality=88, method=6)
    ART.write_text(
        "// Generated by reference/ink-pages/about-closing/build_about_closing.py. Do not edit by hand.\n"
        "// The About page's closing painting (Mo picked B, November 13, 2026): low tide on the Monterey\n"
        "// coast, a curious older woman looks into a tide pool with a hand lens while a park naturalist\n"
        "// points to a sea star; its paper divided out so it multiplies onto the page.\n"
        "export const closingTidepool = {\n"
        f'  src: "{URL}/{NAME}.webp",\n'
        f"  width: {img.width},\n"
        f"  height: {img.height},\n"
        "} as const;\n",
        encoding="utf-8",
        newline="\n",
    )
    size = (SITE / f"{NAME}.webp").stat().st_size
    print(f"{NAME}: {img.width} x {img.height}, shape {img.width / img.height:.4f}, {size // 1024} KB")
    print(ART.relative_to(ROOT))


if __name__ == "__main__":
    main()
